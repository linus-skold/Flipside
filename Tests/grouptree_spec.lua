local ns = {}
assert(loadfile("Core/ItemString.lua"))("Flipside", ns)
assert(loadfile("Services/GroupTree.lua"))("Flipside", ns)
local G = ns.GroupTree

local function chain(d, n)
    local id = 1
    for i = 1, n do
        id = assert(G.Create(d, id, "L" .. i))
    end
    return id
end

describe("GroupTree", function()
    local d
    before_each(function()
        d = G.NewData()
    end)

    describe("NewData and Create", function()
        it("has only the Base group", function()
            assert.are.equal("Base", G.Name(d, 1))
            assert.is_nil(G.Parent(d, 1))
            assert.are.equal(0, G.Depth(d, 1))
            assert.are.equal(2, d.nextID)
            assert.is_true(G.Validate(d))
        end)

        it("creates groups with new ids", function()
            local a = G.Create(d, 1, "Herbs")
            local b = G.Create(d, a, "Flowers")
            assert.are.equal(2, a)
            assert.are.equal(3, b)
            assert.are.equal(a, G.Parent(d, b))
            assert.are.equal(2, G.Depth(d, b))
            assert.is_true(G.Exists(d, b))
            assert.is_false(G.Exists(d, 99))
        end)

        it("refuses an unknown parent", function()
            local id, msg = G.Create(d, 99, "X")
            assert.is_nil(id)
            assert.is_string(msg)
        end)
    end)

    describe("names", function()
        it("trims the name", function()
            local id = G.Create(d, 1, "  Herbs \t")
            assert.are.equal("Herbs", G.Name(d, id))
        end)

        it("refuses empty, blank and non-string names", function()
            assert.is_nil(G.Create(d, 1, ""))
            assert.is_nil(G.Create(d, 1, "   "))
            assert.is_nil(G.Create(d, 1, 5))
            assert.is_nil(G.Create(d, 1, nil))
        end)

        it("checks the length limit", function()
            assert.is_truthy(G.Create(d, 1, string.rep("a", 40)))
            assert.is_nil(G.Create(d, 1, string.rep("b", 41)))
            assert.is_truthy(G.Create(d, 1, "  " .. string.rep("c", 40) .. "  "))
        end)

        it("refuses a duplicate in the same parent, ignoring case", function()
            G.Create(d, 1, "Herbs")
            local id, msg = G.Create(d, 1, "hERBS")
            assert.is_nil(id)
            assert.is_string(msg)
        end)

        it("allows the same name in another parent", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            assert.is_truthy(G.Create(d, a, "Same"))
            assert.is_truthy(G.Create(d, b, "Same"))
        end)

        it("does not use up an id on failure", function()
            G.Create(d, 1, "A")
            G.Create(d, 1, "A")
            assert.are.equal(3, d.nextID)
        end)
    end)

    describe("depth limit", function()
        it("allows 8 levels below Base and refuses the 9th", function()
            local id = chain(d, 8)
            assert.are.equal(8, G.Depth(d, id))
            local nid, msg = G.Create(d, id, "Too deep")
            assert.is_nil(nid)
            assert.is_string(msg)
        end)
    end)

    describe("Rename", function()
        it("renames a group", function()
            local a = G.Create(d, 1, "A")
            assert.is_true(G.Rename(d, a, " B "))
            assert.are.equal("B", G.Name(d, a))
        end)

        it("allows a change of case of its own name", function()
            local a = G.Create(d, 1, "herbs")
            assert.is_true(G.Rename(d, a, "Herbs"))
            assert.are.equal("Herbs", G.Name(d, a))
        end)

        it("refuses a sibling name", function()
            G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            local ok, msg = G.Rename(d, b, "a")
            assert.is_nil(ok)
            assert.is_string(msg)
            assert.are.equal("B", G.Name(d, b))
        end)

        it("refuses a bad name and an unknown group", function()
            local a = G.Create(d, 1, "A")
            assert.is_nil(G.Rename(d, a, ""))
            assert.is_nil(G.Rename(d, 99, "X"))
        end)

        it("refuses to rename Base", function()
            assert.is_nil(G.Rename(d, 1, "Root"))
            assert.are.equal("Base", G.Name(d, 1))
        end)
    end)

    describe("Move", function()
        it("moves a group with its sub-groups", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            local c = G.Create(d, a, "C")
            assert.is_true(G.Move(d, a, b))
            assert.are.equal(b, G.Parent(d, a))
            assert.are.equal(3, G.Depth(d, c))
        end)

        it("refuses a cycle", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            assert.is_nil(G.Move(d, a, a))
            assert.is_nil(G.Move(d, a, b))
            assert.are.equal(1, G.Parent(d, a))
        end)

        it("refuses a move that gets too deep", function()
            local deep = chain(d, 7)
            local a = G.Create(d, 1, "A")
            G.Create(d, a, "A child")
            assert.is_nil(G.Move(d, a, deep))
            local single = G.Create(d, 1, "Single")
            assert.is_true(G.Move(d, single, deep))
            assert.are.equal(8, G.Depth(d, single))
        end)

        it("refuses a duplicate name in the new parent", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            G.Create(d, b, "x")
            local x = G.Create(d, a, "X")
            assert.is_nil(G.Move(d, x, b))
            assert.are.equal(a, G.Parent(d, x))
        end)

        it("allows a move to the same parent", function()
            local a = G.Create(d, 1, "A")
            assert.is_true(G.Move(d, a, 1))
        end)

        it("refuses to move Base and an unknown group or parent", function()
            local a = G.Create(d, 1, "A")
            assert.is_nil(G.Move(d, 1, a))
            assert.is_nil(G.Move(d, 99, a))
            assert.is_nil(G.Move(d, a, 99))
        end)
    end)

    describe("Delete", function()
        it("removes the group and sub-groups and returns the ids", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            local c = G.Create(d, b, "C")
            local other = G.Create(d, 1, "Other")
            local ok, ids = G.Delete(d, a)
            assert.is_true(ok)
            table.sort(ids)
            assert.are.same({ a, b, c }, ids)
            assert.is_false(G.Exists(d, a))
            assert.is_false(G.Exists(d, c))
            assert.is_true(G.Exists(d, other))
            assert.is_true(G.Validate(d))
        end)

        it("moves items to the parent group", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            local c = G.Create(d, b, "C")
            G.AddItem(d, "100", b)
            G.AddItem(d, "200", c)
            G.AddItem(d, "300", a)
            G.Delete(d, b)
            assert.are.equal(a, G.GroupOf(d, "100"))
            assert.are.equal(a, G.GroupOf(d, "200"))
            assert.are.equal(a, G.GroupOf(d, "300"))
        end)

        it("removes items if the parent is Base", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            G.AddItem(d, "100", a)
            G.AddItem(d, "200", b)
            G.Delete(d, a)
            assert.is_nil(d.items["100"])
            assert.is_nil(d.items["200"])
            assert.are.equal(1, G.GroupOf(d, "100"))
        end)

        it("removes attachments of deleted groups only", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            G.Attach(d, a, "selling", 1)
            G.Attach(d, b, "buying", 2)
            G.Attach(d, 1, "selling", 3)
            G.Delete(d, b)
            assert.is_nil(d.attach[b])
            assert.are.equal(1, G.Attached(d, a, "selling"))
            assert.are.equal(3, G.Attached(d, 1, "selling"))
        end)

        it("refuses Base and unknown groups", function()
            assert.is_nil(G.Delete(d, 1))
            assert.is_nil(G.Delete(d, 99))
        end)

        it("never reuses ids", function()
            local a = G.Create(d, 1, "A")
            G.Delete(d, a)
            local b = G.Create(d, 1, "A")
            assert.are.equal(a + 1, b)
            G.Delete(d, b)
            assert.are.equal(b + 1, G.Create(d, 1, "A"))
        end)
    end)

    describe("Children, Path and Walk", function()
        it("sorts children by name, ignoring case", function()
            local z = G.Create(d, 1, "zeta")
            local b = G.Create(d, 1, "Beta")
            local a = G.Create(d, 1, "alpha")
            assert.are.same({ a, b, z }, G.Children(d, 1))
            assert.are.same({}, G.Children(d, z))
        end)

        it("returns the path from Base", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            assert.are.same({ "Base" }, G.Path(d, 1))
            assert.are.same({ "Base", "A", "B" }, G.Path(d, b))
            assert.is_nil(G.Path(d, 99))
        end)

        it("walks depth first in sorted order", function()
            local b = G.Create(d, 1, "B")
            local a = G.Create(d, 1, "A")
            local a2 = G.Create(d, a, "A2")
            local a1 = G.Create(d, a, "A1")
            local order, depths = {}, {}
            G.Walk(d, function(id, depth)
                order[#order + 1] = id
                depths[#depths + 1] = depth
            end)
            assert.are.same({ 1, a, a1, a2, b }, order)
            assert.are.same({ 0, 1, 2, 2, 1 }, depths)
        end)
    end)

    describe("membership", function()
        it("moves an item between groups (exclusive)", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            assert.is_true(G.AddItem(d, "2589", a))
            assert.is_true(G.AddItem(d, "2589", b))
            assert.are.same({}, G.ItemsIn(d, a))
            assert.are.same({ "2589" }, G.ItemsIn(d, b))
        end)

        it("removes the entry when added to Base", function()
            local a = G.Create(d, 1, "A")
            G.AddItem(d, "2589", a)
            assert.is_true(G.AddItem(d, "2589", 1))
            assert.is_nil(d.items["2589"])
        end)

        it("returns an item to Base with RemoveItem", function()
            local a = G.Create(d, 1, "A")
            G.AddItem(d, "2589", a)
            G.RemoveItem(d, "2589")
            assert.are.equal(1, G.GroupOf(d, "2589"))
        end)

        it("finds the group by exact key, then base key, else Base", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            G.AddItem(d, "12345", a)
            G.AddItem(d, "12345#s-34", b)
            assert.are.equal(b, G.GroupOf(d, "12345#s-34"))
            assert.are.equal(a, G.GroupOf(d, "12345#b10,20"))
            assert.are.equal(a, G.GroupOf(d, "12345"))
            assert.are.equal(1, G.GroupOf(d, "999"))
            assert.are.equal(1, G.GroupOf(d, "bad key"))
        end)

        it("refuses an invalid key and an unknown group", function()
            local a = G.Create(d, 1, "A")
            local ok, msg = G.AddItem(d, "item:123", a)
            assert.is_nil(ok)
            assert.is_string(msg)
            assert.is_nil(G.AddItem(d, 5, a))
            assert.is_nil(G.AddItem(d, "100", 99))
            assert.is_nil(next(d.items))
        end)

        it("lists sorted keys and an empty array for Base", function()
            local a = G.Create(d, 1, "A")
            G.AddItem(d, "300", a)
            G.AddItem(d, "100#s5", a)
            G.AddItem(d, "100", a)
            assert.are.same({ "100", "100#s5", "300" }, G.ItemsIn(d, a))
            assert.are.same({}, G.ItemsIn(d, 1))
        end)

        it("counts items, also recursive", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            G.AddItem(d, "1", a)
            G.AddItem(d, "2", b)
            G.AddItem(d, "3", b)
            assert.are.equal(1, G.CountItems(d, a, false))
            assert.are.equal(3, G.CountItems(d, a, true))
            assert.are.equal(2, G.CountItems(d, b, true))
            assert.are.equal(0, G.CountItems(d, 1, false))
            assert.are.equal(3, G.CountItems(d, 1, true))
        end)
    end)

    describe("attachments", function()
        it("attaches, reads and detaches", function()
            local a = G.Create(d, 1, "A")
            assert.is_true(G.Attach(d, a, "selling", 3))
            assert.are.equal(3, G.Attached(d, a, "selling"))
            assert.is_nil(G.Attached(d, a, "buying"))
            G.Attach(d, a, "selling", 4)
            assert.are.equal(4, G.Attached(d, a, "selling"))
            G.Detach(d, a, "selling")
            assert.is_nil(G.Attached(d, a, "selling"))
            assert.is_true(G.Validate(d))
        end)

        it("refuses bad input", function()
            assert.is_nil(G.Attach(d, 99, "selling", 1))
            assert.is_nil(G.Attach(d, 1, "", 1))
            assert.is_nil(G.Attach(d, 1, "selling", 0))
            assert.is_nil(G.Attach(d, 1, "selling", "x"))
        end)

        it("inherits from parent, grandparent and Base", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            local c = G.Create(d, b, "C")
            G.Attach(d, 1, "selling", 9)
            local op, from = G.Effective(d, c, "selling")
            assert.are.equal(9, op)
            assert.are.equal(1, from)
            G.Attach(d, a, "selling", 5)
            op, from = G.Effective(d, c, "selling")
            assert.are.equal(5, op)
            assert.are.equal(a, from)
            G.Attach(d, b, "selling", 6)
            op, from = G.Effective(d, c, "selling")
            assert.are.equal(6, op)
            assert.are.equal(b, from)
        end)

        it("lets an own attachment override", function()
            local a = G.Create(d, 1, "A")
            G.Attach(d, 1, "buying", 1)
            G.Attach(d, a, "buying", 2)
            local op, from = G.Effective(d, a, "buying")
            assert.are.equal(2, op)
            assert.are.equal(a, from)
        end)

        it("returns nil if nothing is attached", function()
            local a = G.Create(d, 1, "A")
            assert.is_nil(G.Effective(d, a, "selling"))
            assert.is_nil(G.Effective(d, 99, "selling"))
        end)

        it("removes an operation from all groups", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, 1, "B")
            G.Attach(d, a, "selling", 7)
            G.Attach(d, b, "buying", 7)
            G.Attach(d, b, "selling", 8)
            G.DetachOperation(d, 7)
            assert.is_nil(G.Attached(d, a, "selling"))
            assert.is_nil(G.Attached(d, b, "buying"))
            assert.are.equal(8, G.Attached(d, b, "selling"))
            assert.is_nil(d.attach[a])
            assert.is_true(G.Validate(d))
        end)
    end)

    describe("Validate", function()
        it("accepts a full tree", function()
            local a = G.Create(d, 1, "A")
            local b = G.Create(d, a, "B")
            G.AddItem(d, "100#s-3", b)
            G.Attach(d, b, "selling", 2)
            assert.is_true(G.Validate(d))
        end)

        it("accepts a tree at the depth limit", function()
            chain(d, 8)
            assert.is_true(G.Validate(d))
        end)

        local function broken(name, mutate)
            it("refuses " .. name, function()
                local a = G.Create(d, 1, "A")
                G.Create(d, a, "B")
                G.AddItem(d, "100", a)
                G.Attach(d, a, "selling", 2)
                mutate(d, a)
                local ok, msg = G.Validate(d)
                assert.is_false(ok)
                assert.is_string(msg)
            end)
        end

        it("refuses a non-table", function()
            assert.is_false(G.Validate(nil))
            assert.is_false(G.Validate("x"))
        end)

        broken("a wrong version", function(x) x.version = 2 end)
        broken("a missing items table", function(x) x.items = nil end)
        broken("a bad nextID", function(x) x.nextID = 2 end)
        broken("a missing Base", function(x) x.nodes[1] = nil end)
        broken("a renamed Base", function(x) x.nodes[1].name = "Root" end)
        broken("a Base with a parent", function(x, a) x.nodes[1].parent = a end)
        broken("an unknown parent", function(x, a) x.nodes[a].parent = 50 end)
        broken("a cycle", function(x, a) x.nodes[1 + 1].parent = 3; x.nodes[3].parent = a end)
        broken("an untrimmed name", function(x, a) x.nodes[a].name = " A" end)
        broken("a long name", function(x, a) x.nodes[a].name = string.rep("a", 41) end)
        broken("a duplicate sibling", function(x) x.nodes[4] = { name = "a", parent = 1 }; x.nextID = 5 end)
        broken("a too deep tree", function(x)
            local p = 3
            for i = 4, 12 do
                x.nodes[i] = { name = "n" .. i, parent = p }
                p = i
            end
            x.nextID = 13
        end)
        broken("an invalid item key", function(x, a) x.items["item:1"] = a end)
        broken("an item in an unknown group", function(x) x.items["100"] = 77 end)
        broken("an item stored in Base", function(x) x.items["100"] = 1 end)
        broken("an attachment on an unknown group", function(x) x.attach[77] = { selling = 1 } end)
        broken("an invalid operation id", function(x, a) x.attach[a].selling = "x" end)
    end)
end)
