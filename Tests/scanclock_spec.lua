local ns = {}
assert(loadfile("Services/ScanClock.lua"))("Flipside", ns)
local C = ns.ScanClock

describe("ScanClock", function()
    it("has the constants", function()
        assert.are.equal(86400, C.SECONDS_PER_DAY)
        assert.are.equal(900, C.COOLDOWN_SECONDS)
        assert.are.equal(60, C.EVENT_TIMEOUT_SECONDS)
        assert.are.equal(30, C.ITEM_LOAD_TIMEOUT_SECONDS)
        assert.are.equal(4, C.MAX_SNAPSHOTS_PER_DAY)
        assert.are.equal(60, C.RETENTION_DAYS_DEFAULT)
        assert.are.equal(14, C.MARKET_WINDOW_DAYS)
        assert.are.equal(2.2, C.MARKET_HALF_LIFE_DAYS)
        assert.are.equal("standard", C.RULESET_DEFAULT)
    end)

    describe("DayOf", function()
        it("handles day boundaries", function()
            assert.are.equal(0, C.DayOf(0))
            assert.are.equal(0, C.DayOf(86399))
            assert.are.equal(1, C.DayOf(86400))
        end)

        it("handles a real 2026 time", function()
            assert.are.equal(20739, C.DayOf(1791930182))
            assert.are.equal(1791849600, C.DayStart(20739))
        end)

        it("accepts fractional seconds", function()
            assert.are.equal(0, C.DayOf(86399.9))
            assert.are.equal(1, C.DayOf(86400.5))
        end)

        it("rejects invalid input", function()
            assert.has_error(function() C.DayOf(-1) end)
            assert.has_error(function() C.DayOf(nil) end)
            assert.has_error(function() C.DayOf("5") end)
            assert.has_error(function() C.DayOf(0 / 0) end)
            assert.has_error(function() C.DayOf(math.huge) end)
        end)
    end)

    describe("DayStart", function()
        it("returns midnight UTC", function()
            assert.are.equal(0, C.DayStart(0))
            assert.are.equal(86400, C.DayStart(1))
        end)

        it("round-trips with DayOf", function()
            assert.are.equal(500, C.DayOf(C.DayStart(500)))
            assert.are.equal(499, C.DayOf(C.DayStart(500) - 1))
        end)

        it("rejects invalid input", function()
            assert.has_error(function() C.DayStart(-1) end)
            assert.has_error(function() C.DayStart(1.5) end)
            assert.has_error(function() C.DayStart(nil) end)
            assert.has_error(function() C.DayStart("1") end)
            assert.has_error(function() C.DayStart(math.huge) end)
        end)
    end)

    describe("HoursBetween", function()
        it("returns whole, fractional and negative hours", function()
            assert.are.equal(1, C.HoursBetween(0, 3600))
            assert.are.equal(0.25, C.HoursBetween(0, 900))
            assert.are.equal(-2, C.HoursBetween(7200, 0))
        end)
    end)

    describe("IsNewDay", function()
        it("is true for nil lastDay", function()
            assert.is_true(C.IsNewDay(nil, 0))
        end)

        it("is false on the same day", function()
            assert.is_false(C.IsNewDay(1, 86400))
            assert.is_false(C.IsNewDay(1, 172799))
        end)

        it("is true on a later day", function()
            assert.is_true(C.IsNewDay(1, 172800))
        end)

        it("is false for an earlier day", function()
            assert.is_false(C.IsNewDay(5, 86400))
        end)
    end)
end)
