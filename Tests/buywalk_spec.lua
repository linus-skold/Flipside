local manifest = require("Tests.manifest")

local function loadWalk()
    local ns = {}
    assert(loadfile(manifest.path("BuyingPlan")))("Flipside", ns)
    assert(loadfile(manifest.path("BuyWalk")))("Flipside", ns)
    return ns.BuyWalk
end

describe("BuyWalk", function()
    local BuyWalk

    before_each(function()
        BuyWalk = loadWalk()
    end)

    describe("NoneLeft", function()
        it("is true for the reasons that mean no buyable level", function()
            assert.is_true(BuyWalk.NoneLeft(nil, "nothing left to buy"))
            assert.is_true(BuyWalk.NoneLeft({}, "above max price"))
            assert.is_true(BuyWalk.NoneLeft({}, "own listing"))
            assert.is_true(BuyWalk.NoneLeft({}, "own listing below the selected level"))
            assert.is_true(BuyWalk.NoneLeft(nil, nil))
        end)

        it("is false when a level can be bought or the client waits", function()
            assert.is_false(BuyWalk.NoneLeft({}, nil))
            assert.is_false(BuyWalk.NoneLeft({}, "waiting for the Auction House"))
            assert.is_false(BuyWalk.NoneLeft({}, "buying is not available"))
            assert.is_false(BuyWalk.NoneLeft({}, "search first"))
        end)
    end)

    describe("IsFullScan", function()
        it("accepts a full scan that saved its data", function()
            assert.is_true(BuyWalk.IsFullScan({ result = "ok" }))
            assert.is_true(BuyWalk.IsFullScan({ result = "ok", mode = "full" }))
        end)

        it("refuses a partial, failed or cancelled scan and other modes", function()
            assert.is_false(BuyWalk.IsFullScan({ result = "partial", mode = "full" }))
            assert.is_false(BuyWalk.IsFullScan({ result = "error" }))
            assert.is_false(BuyWalk.IsFullScan({ result = "cancelled" }))
            assert.is_false(BuyWalk.IsFullScan({ result = "ok", mode = "page" }))
            assert.is_false(BuyWalk.IsFullScan(nil))
        end)
    end)

    describe("Decide", function()
        it("scans when the scan can start", function()
            assert.are.equal("scan", (BuyWalk.Decide({ canStart = true })))
        end)

        it("walks over the list on cooldown when the list comes from a full scan", function()
            assert.are.equal("walk", (BuyWalk.Decide({ canStart = false, reason = "cooldown" })))
            assert.are.equal("walk", (BuyWalk.Decide({ canStart = false, reason = "client" })))
        end)

        it("starts nothing on cooldown with no usable list", function()
            local action, text = BuyWalk.Decide({
                canStart = false, reason = "cooldown", state = "Run a full scan first.",
            })
            assert.are.equal("empty", action)
            assert.are.equal("Run a full scan first.", text)
            action, text = BuyWalk.Decide({ canStart = false, reason = "cooldown", partial = true })
            assert.are.equal("empty", action)
            assert.are.equal("The last scan was partial. Run a full scan.", text)
        end)

        it("refuses for another reason", function()
            local action, reason = BuyWalk.Decide({ canStart = false, reason = "ah-closed" })
            assert.are.equal("refuse", action)
            assert.are.equal("ah-closed", reason)
        end)
    end)

    describe("the walk", function()
        it("goes through the keys in order and ends after the last", function()
            local walk = BuyWalk.New()
            assert.is_false(walk:IsActive())
            assert.are.equal("a", (walk:Begin({ "a", "b" })))
            assert.is_true(walk:IsWalking())
            assert.are.equal("a", walk:Current())
            assert.are.equal("b", walk:Advance())
            local key, text = walk:Advance()
            assert.is_nil(key)
            assert.are.equal(BuyWalk.TEXT.done, text)
            assert.is_false(walk:IsActive())
        end)

        it("does not start with no keys", function()
            local walk = BuyWalk.New()
            local key, text = walk:Begin({})
            assert.is_nil(key)
            assert.are.equal(BuyWalk.TEXT.empty, text)
            assert.is_false(walk:IsActive())
        end)

        it("stops at once", function()
            local walk = BuyWalk.New()
            walk:Begin({ "a", "b" })
            assert.is_true(walk:Stop())
            assert.is_nil(walk:Current())
            assert.is_nil(walk:Advance())
            assert.is_false(walk:Stop())
        end)

        it("waits for the scan, then for the list, after a full scan", function()
            local walk = BuyWalk.New()
            walk:BeginScan()
            assert.is_true(walk:IsWaitingForScan())
            assert.are.equal("list", (walk:OnScanFinished({ result = "ok", mode = "full" })))
            assert.is_true(walk:IsWaitingForList())
            assert.are.equal("a", (walk:Begin({ "a" })))
            assert.is_true(walk:IsWalking())
        end)

        it("waits for the list with no scan", function()
            local walk = BuyWalk.New()
            walk:BeginList()
            assert.is_true(walk:IsWaitingForList())
            assert.are.equal("a", (walk:Begin({ "a" })))
        end)

        it("stops when the scan is partial or fails", function()
            local walk = BuyWalk.New()
            walk:BeginScan()
            local verdict, text = walk:OnScanFinished({ result = "partial", mode = "full" })
            assert.are.equal("stop", verdict)
            assert.are.equal(BuyWalk.TEXT.partial, text)
            assert.is_false(walk:IsActive())
            walk:BeginScan()
            verdict, text = walk:OnScanFinished({ result = "error" })
            assert.are.equal("stop", verdict)
            assert.are.equal(BuyWalk.TEXT.failed, text)
        end)

        it("ignores a scan end when it did not wait for a scan", function()
            local walk = BuyWalk.New()
            assert.is_nil(walk:OnScanFinished({ result = "ok" }))
            walk:Begin({ "a" })
            assert.is_nil(walk:OnScanFinished({ result = "partial" }))
            assert.is_true(walk:IsWalking())
        end)
    end)
end)
